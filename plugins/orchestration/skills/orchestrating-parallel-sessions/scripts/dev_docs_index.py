"""DEV-DOCS-INDEX.md is a VIEW, computed from the artifacts - never a file anyone appends to.

<!-- route-tags: dev docs index generate view planned development doc discovery duplicate sprawl -->
<!-- cornerstone: knowledge-routing -->

WHY THIS EXISTS, AND WHAT IT COST TO LEARN
------------------------------------------
Project CLAUDE.md, the human 2026-08-17: *"if it's an index, it must be generated, never hand-kept in
any way."* DEV-DOCS-INDEX was the last hand-kept one, and it had already drifted the way every
hand-kept index in this workspace has: on 2026-08-12 four of its rows pointed at
`docs/superpowers/specs/`, a directory the files had been moved out of, and the correction lived
on `main` while the branch a lane was reading had the wrong paths still.

⭐ THE TEST THAT MADE IT A DOCUMENT RATHER THAN AN INDEX: *if deleting the file would lose
information, it was never an index.* Deleting it used to lose 82 authored summaries that existed
nowhere else. Now it loses nothing - every summary lives ON the artifact it describes, and this
script rebuilds the file from them.

WHERE EACH PART LIVES, AND WHY THERE
------------------------------------
  MEMBERSHIP + PATH   derived, every run. An artifact is in the index because it CARRIES a
                      `<!-- dev-doc: ... -->` marker, and its path is where the file actually
                      is. A doc that moves takes its row with it; that is the whole point.
  THE SUMMARY         authored, and it lives ON THE ARTIFACT (`<!-- summary: ... -->`). It is
                      judgement and cannot be generated, so it is kept where it cannot be
                      separated from the thing it describes.
  SECTIONS + PROSE    authored, in `dev_docs_sections.json` beside this script - the same
                      ENGINE/VOCABULARY split as knowledge_pages.py and facets.py. A section
                      grouping is a claim about the business, not a fact about the corpus.

THE MARKER BLOCK an artifact carries
------------------------------------
    <!-- dev-doc: section=<slug> order=<n> [parent=<basename>] [path=<shown>] [url=<href>]
                  [also=<extra file>] -->
    <!-- dev-doc-title: <plain text title> -->
    <!-- summary: <the row's authored text: type, summary, status> -->

⛔ ORPHANS ARE PRINTED, NOT DROPPED. Three rows named artifacts that are on no branch of the
working tree (one is an unmerged PR; two exist in no commit anywhere). Their authored text is
held in the JSON's `orphans` list and rendered with a visible warning, because a row that
quietly disappears is exactly the data loss this conversion was told to avoid. When the file
appears, `--check` says so and the text moves onto it.

    dev_docs_index.py            report drift; write nothing (exit 1 if the view is stale)
    dev_docs_index.py --write    regenerate DEV-DOCS-INDEX.md
    dev_docs_index.py --check    orphan/marker health: unresolved orphans, unknown sections
    dev_docs_index.py --selftest

ASCII output. Fails loudly rather than writing a partial index.
"""
