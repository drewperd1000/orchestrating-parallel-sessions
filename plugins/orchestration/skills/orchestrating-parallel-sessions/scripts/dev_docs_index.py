#!/usr/bin/env python3
"""DEV-DOCS-INDEX.md is a VIEW, computed from the artifacts - never a file anyone appends to.

<!-- route-tags: dev docs index generate view planned development doc discovery duplicate sprawl -->
<!-- cornerstone: knowledge-routing -->

WHERE EACH PART LIVES, AND WHY THERE
------------------------------------
  MEMBERSHIP + PATH   derived, every run. An artifact is in the index because it CARRIES a
                      `<!-- dev-doc: ... -->` marker, and its path is where the file actually
                      is. A doc that moves takes its row with it; that is the whole point.
  THE SUMMARY         authored, and it lives ON THE ARTIFACT (`<!-- summary: ... -->`). It is
                      judgement and cannot be generated, so it is kept where it cannot be
                      separated from the thing it describes.
  SECTIONS + PROSE    authored, in `dev_docs_sections.json` beside this script - the same
                      ENGINE/VOCABULARY split as knowledge_pages.py and facets.py. A section
                      grouping is a claim about the business, not a fact about the corpus.

THE MARKER BLOCK an artifact carries
------------------------------------
    <!-- dev-doc: section=<slug> order=<n> [parent=<basename>] [path=<shown>] [url=<href>]
                  [also=<extra file>] -->
    <!-- dev-doc-title: <plain text title> -->
    <!-- summary: <the row's authored text: type, summary, status> -->

    dev_docs_index.py            report drift; write nothing (exit 1 if the view is stale)
    dev_docs_index.py --write    regenerate DEV-DOCS-INDEX.md
    dev_docs_index.py --check    orphan/marker health: unresolved orphans, unknown sections
    dev_docs_index.py --selftest

ASCII output. Fails loudly rather than writing a partial index.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from workspace_paths import WS, MEM  # noqa: E402
from mentions import declaration_region, outside_fences  # noqa: E402 - ONE definition
import cloud_layout  # noqa: E402 - is_generated_copy, the one rule for .shared/cloud/
import private_folders  # noqa: E402 - the folders outsiders write, ONE definition
import leftover_files  # noqa: E402 - untracked files origin/main deleted, ONE definition
try:
    import generated_writes  # noqa: E402 - what --write put on disk, ONE definition
except ImportError:  # a partial delivery must not stop a write; the copy is just not recorded
    generated_writes = None
try:
    from no_window import flags  # noqa: E402
except ImportError:  # a partial delivery must not take the tool down
    def flags(extra=0):
        return extra

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

OUT = WS / "DEV-DOCS-INDEX.md"
DATA_FILE = Path(__file__).resolve().parent / "dev_docs_sections.json"

BANNER = ("<!-- GENERATED by .shared/scripts/dev_docs_index.py - do not hand-edit. "
          "A row's summary lives ON its artifact as `<!-- summary: ... -->`; the section "
          "groupings live in dev_docs_sections.json beside that script. -->")

DEV_DOC = re.compile(r"^<!--\s*dev-doc:\s*(?P<attrs>[^>]*?)\s*-->", re.M)
DEV_TITLE = re.compile(r"<!--\s*dev-doc-title:\s*(?P<t>.+?)\s*-->", re.S)
SUMMARY = re.compile(r"<!--\s*summary:\s*(?P<s>.+?)\s*-->", re.S)

# Directories that hold no knowledge and cost seconds to walk.
SKIP_DIRS = {"node_modules", ".git", "dist", "build", ".next", ".astro", "coverage",
             "__pycache__", ".venv", "venv", ".code-graph", "out", ".turbo", ".cache",
             "captured_notes", "research_log",
             ".worktrees"}
SKIP_DIRS |= set(private_folders.NAMES)


def _load():
    try:
        return json.loads(DATA_FILE.read_text(encoding="utf-8"))
    except Exception as e:                       # a missing shape is a real state, not a crash
        print("dev-docs index: cannot read %s (%s)" % (DATA_FILE.name, e), file=sys.stderr)
        return {}


DATA = _load()
STAMP_RE = re.compile(r"^\*\*Last updated: ([^*]+)\*\*")
STAMP_MARK = "<<LAST-UPDATED>>"


def _stamp_line(when):
    return ("**Last updated: %s** _(stamped when the rows last changed, never hand-written. "
            "A run that changes nothing keeps the date it found.)_" % when)


def _without_stamp(text):
    """Everything except the Last-updated line - so the date is never why the date changes."""
    return "\n".join(l for l in (text or "").split("\n") if not STAMP_RE.match(l))


def _resolve_stamp(new_text, old_text):
    """Today if the rows moved, otherwise the date already on disk. This is what converges.
    """
    import datetime as _dt
    prev = None
    for l in (old_text or "").split("\n"):
        m = STAMP_RE.match(l)
        if m:
            prev = m.group(1).strip()
            break
    same = _without_stamp(new_text) == _without_stamp(old_text)
    when = prev if (same and prev) else _dt.date.today().strftime("%d-%b-%Y")
    return new_text.replace(_stamp_line(STAMP_MARK), _stamp_line(when))

SECTIONS = DATA.get("sections", [])
SECTION_ORDER = {s["slug"]: i for i, s in enumerate(SECTIONS)}


def collapse(s):
    return re.sub(r"\s+", " ", s).strip()


def read_markers(text):
    """{attrs, title, summary} for a marked artifact, or None. The ONE reader of the block."""
    m = DEV_DOC.search(text)
    if not m:
        return None
    attrs = {}
    for kv in m.group("attrs").split():
        if "=" in kv:
            k, v = kv.split("=", 1)
            attrs[k] = v
    t = DEV_TITLE.search(text)
    s = SUMMARY.search(text)
    return {"attrs": attrs,
            "title": collapse(t.group("t")) if t else None,
            "summary": collapse(s.group("s")) if s else None}


def harvest(base=None, skipped=None):
    """Every artifact carrying the marker, under the workspace or the memory store, less the
    LEFTOVERS: untracked files whose path origin/main's history deleted (leftover_files.py).

    `base` is a commit a landing job pinned, and makes the leftover test strict (it
    raises leftover_files.CannotCheck when it cannot run). None is a run by hand: origin/main, and every artifact kept when the test cannot run, as
    before. `skipped`, when a list, receives each leftover dropped."""
    found = []
    for store in (WS, MEM):
        if not store.exists():
            continue
        if private_folders.in_private_folder(store):
            continue
        for root, dirs, files in os.walk(store):
            dirs[:] = [d for d in dirs
                       if d not in SKIP_DIRS and not private_folders.is_private_name(d)
                       and not private_folders.is_link(os.path.join(root, d))
                       and not _in_other_worktree(os.path.join(root, d))
                       and not _is_gitless_lane_dir(root, d)
                       and not cloud_layout.is_generated_copy(os.path.join(root, d))]
            for f in files:
                if not f.endswith(".md"):
                    continue
                p = Path(root) / f
                if cloud_layout.is_generated_copy(p) or private_folders.is_link(p):
                    continue
                if p == OUT:
                    continue
                try:
                    raw = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    continue
                head = outside_fences(declaration_region(raw, p))
                if "\n<!-- dev-doc:" not in head and not head.startswith("<!-- dev-doc:"):
                    continue
                if "<!-- GENERATED by" in head[:400]:
                    continue
                mk = read_markers(head)
                if mk:
                    found.append({"path": p, **mk})
    left = []
    found = leftover_files.drop(found, WS, base, left)
    if left:
        print(leftover_files.note(len(left)))
    if skipped is not None:
        skipped.extend(left)
    return found


def _linkable(p):
    """Inside the <your-workspace> repo itself - i.e. no intervening `.git` on the way down.
    """
    try:
        rel = p.relative_to(WS)
    except ValueError:
        return None
    parts = rel.as_posix().split("/")
    for k in range(1, len(parts)):
        if (WS.joinpath(*parts[:k]) / ".git").exists():
            return None
    return rel.as_posix()


def _reader_ws():
    """The MAIN working tree - where a reader opens these files, not where we are generating.
    """
    try:
        import subprocess
        r = subprocess.run(["git", "worktree", "list", "--porcelain"],
                           capture_output=True, text=True, timeout=15, cwd=str(WS),
                           creationflags=flags())
        for line in r.stdout.split("\n"):
            if line.startswith("worktree "):
                return Path(line[len("worktree "):].strip())
    except Exception:
        pass
    return WS


READER_WS = _reader_ws()


def _other_worktree_roots():
    """Every registered worktree EXCEPT the one a reader opens - the directories to never walk.
    """
    roots = set()
    try:
        import subprocess
        r = subprocess.run(["git", "worktree", "list", "--porcelain"],
                           capture_output=True, text=True, timeout=15, cwd=str(WS),
                           creationflags=flags())
        main = None
        for line in r.stdout.split("\n"):
            if not line.startswith("worktree "):
                continue
            p = Path(line[len("worktree "):].strip())
            if main is None:
                main = p.resolve()
                continue
            try:
                roots.add(p.resolve())
            except OSError:
                continue
    except Exception:
        pass                       # no git, no prune - the walk is then what it always was
    return roots


OTHER_WORKTREES = _other_worktree_roots()


def _is_worktree_dir(path):
    """True when this directory is a WORKTREE of some repo rather than a repo of its own.
    """
    try:
        g = Path(path) / ".git"
        return g.is_file()
    except OSError:
        return False


def _is_gitless_lane_dir(parent, name):
    """True for a child of a worktree root (`worktrees`, `*-worktrees`) that has no `.git`.
    """
    root_name = os.path.basename(os.path.normpath(parent)).lower()
    if root_name != "worktrees" and not root_name.endswith("-worktrees"):
        return False
    try:
        return not (Path(parent) / name / ".git").exists()
    except OSError:
        return False


def _in_other_worktree(path):
    """True when this directory IS, or sits inside, a worktree that is not the reader's."""
    if _is_worktree_dir(path):
        return True
    try:
        rp = Path(path).resolve()
    except OSError:
        return False
    for root in OTHER_WORKTREES:
        if rp == root or root in rp.parents:
            return True
    return False


def _as_reader_path(p):
    """Re-root an absolute path under the MAIN worktree when it sits inside ours."""
    try:
        return (READER_WS / Path(p).relative_to(WS)).as_posix()
    except (ValueError, TypeError):
        return Path(p).as_posix()


def render_row(a, indent=0):
    at = a["attrs"]
    rel = _linkable(a["path"])
    href = at.get("url") or rel
    title = a["title"] or a["path"].name
    head = "**[%s](%s)**" % (title, href) if href else "**%s**" % title
    shown = at.get("path")
    if shown:
        disp = shown if shown.startswith("C:") else (READER_WS / shown).as_posix()
        if shown.endswith("/"):
            disp = disp.rstrip("/") + "/"
    else:
        disp = _as_reader_path(a["path"])
    cols = [head, "`%s`" % disp]
    if at.get("also"):
        cols[-1] += " (+ `%s`)" % at["also"]
    cols.append(a["summary"] or "")
    return "%s- %s" % (" " * indent, " \u00b7 ".join(c for c in cols if c))


def render_orphan(o):
    head = "**[%s](%s)**" % (o["title"], o["href"]) if o.get("href") else "**%s**" % o["title"]
    return ("- \u26a0 **TARGET NOT ON DISK** - %s \u00b7 `%s` \u00b7 %s\n"
            "  \u21b3 *%s. Its authored text is held in `dev_docs_sections.json` until the file "
            "exists; nothing was dropped.*" % (head, o["path"], o["payload"], o["why"]))


def build(base=None, skipped=None):
    """(lines, problems, artifacts) - the whole file, and anything that stopped it being clean.
    `base` and `skipped` go to harvest()."""
    arts = harvest(base, skipped)
    problems = []
    by_section = {}
    for a in arts:
        slug = a["attrs"].get("section")
        if slug not in SECTION_ORDER:
            problems.append("%s declares unknown section `%s`" % (a["path"].name, slug))
            continue
        if not a["summary"]:
            problems.append("%s carries a dev-doc marker but no <!-- summary: --> line"
                            % a["path"].name)
        by_section.setdefault(slug, []).append(a)

    orphans = {}
    for o in DATA.get("orphans", []):
        orphans.setdefault(o["section"], []).append(o)
        if Path(o["path"]).exists():
            problems.append("orphan RESOLVED - %s now exists; move its text onto the artifact "
                            "and delete the orphan entry (run --write to do it automatically)"
                            % o["path"])

    L = [BANNER, "", "# %s" % DATA.get("h1", "DEV-DOCS-INDEX"), "",
         _stamp_line(STAMP_MARK), "",
         DATA.get("header", ""), "",
         "**How this file is built.** Membership and every path are DERIVED: a doc appears "
         "here because it carries a `<!-- dev-doc: section=... -->` marker, and its path is "
         "wherever the file actually is - so a doc that moves takes its row with it. The "
         "one-line summary is authored and lives ON the artifact as `<!-- summary: ... -->`, "
         "which is why deleting this file loses nothing. Section groupings and their intro "
         "prose are authored in `.shared/scripts/dev_docs_sections.json`. Regenerate with "
         "`python <scripts>/dev_docs_index.py --write`.", "",
         "---", ""]

    for s in SECTIONS:
        rows = by_section.get(s["slug"], [])
        orph = orphans.get(s["slug"], [])
        L += ["## %s" % s["title"], ""]
        if s.get("intro"):
            L += [s["intro"], ""]
        if not rows and not orph:
            L += ["*Nothing carries `section=%s` today. That is a finding, not a formatting "
                  "gap.*" % s["slug"], ""]
        # parents first, each followed by its children, then the rest, all by declared order.
        kids = {}
        for a in rows:
            par = a["attrs"].get("parent")
            if par:
                kids.setdefault(par, []).append(a)
        top = [a for a in rows if not a["attrs"].get("parent")]
        top.sort(key=lambda a: int(a["attrs"].get("order", 0)))
        for a in top:
            L.append(render_row(a))
            for k in sorted(kids.get(a["path"].name, []),
                            key=lambda x: int(x["attrs"].get("order", 0))):
                L.append(render_row(k, indent=2))
        for k, v in kids.items():
            if k not in {a["path"].name for a in top}:
                problems.append("parent=%s named by %s is not in this section"
                                % (k, ", ".join(x["path"].name for x in v)))
        for o in sorted(orph, key=lambda x: x["order"]):
            L.append(render_orphan(o))
        L += [""]
        if s.get("rule_after"):
            L += ["---", ""]

    L += ["---", "", "## %s" % DATA.get("excluded_title", "Excluded (and why)"), "",
          DATA.get("excluded", ""), ""]
    return L, problems, arts


def cmd_check():
    _, problems, arts = build()
    print("dev-docs index - marker health")
    print()
    print("  artifacts carrying a dev-doc marker : %d" % len(arts))
    print("  orphan rows (no artifact on disk)   : %d" % len(DATA.get("orphans", [])))
    for o in DATA.get("orphans", []):
        print("     - %s  (%s)" % (o["path"], o["why"]))
    print("  problems                            : %d" % len(problems))
    for p in problems:
        print("     - %s" % p)
    print()
    if problems:
        print("  Each problem above is a row that will not render where it should.")
        return 1
    print("  every marker resolves to a known section, with a summary.")
    return 0


def _missing_declared_stores():
    """Declared nested product repos that are ABSENT from this checkout.

    A worktree is the ordinary way to land here: `git worktree add` checks out this repo and
    nothing else, so every nested product repo is missing and the generator sees a corpus less
    than half the size with no indication anything is wrong.
    """
    try:
        raw = json.loads((Path(__file__).resolve().parent
                          / "facets_vocabulary.json").read_text(encoding="utf-8"))
        repos = [n for n in raw.get("nested_repos", []) if n]
    except Exception:
        return []                        # no vocabulary, no claim - the count check still runs
    return [r for r in repos if not (WS / r).is_dir()]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--allow-shrink", action="store_true",
                    help="write even though the index would lose rows - for a genuine "
                         "deletion, never to get past a partial tree")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if not DATA:
        print("dev-docs index: no %s - nothing generated, nothing on disk touched."
              % DATA_FILE.name)
        return 0
    if a.check:
        return cmd_check()
    if a.write:
        # Self-clearing: a resolved orphan is migrated rather than reported, so it can
        # never again be the reason this index refuses to write. See the function.
        for line in migrate_resolved_orphans():
            print("   MIGRATED: %s" % line)
    lines, problems, arts = build()
    if not arts and OUT.exists():
        print("dev-docs index: the scan found ZERO marked artifacts while %s exists."
              % OUT.name)
        print("   That is a broken scan, not an empty corpus - refusing to overwrite the map.")
        return 1
    new = "\n".join(lines).rstrip("\n") + "\n"
    old = OUT.read_text(encoding="utf-8", errors="replace") if OUT.exists() else None
    # The stamp is decided HERE, where both texts exist, and only from whether the
    # rows moved - so the `old == new` test below stays a true test of convergence.
    new = _resolve_stamp(new, old)

    _roots = {}
    for _a in arts:
        try:
            _rel = Path(_a["path"]).resolve().relative_to(WS.resolve()).parts
        except Exception:
            _roots["(memory)"] = _roots.get("(memory)", 0) + 1
            continue
        _roots[_rel[0] if len(_rel) > 1 else "(workspace root)"] = \
            _roots.get(_rel[0] if len(_rel) > 1 else "(workspace root)", 0) + 1
    if _roots:
        print("   markers per root: %s"
              % ", ".join("%s %d" % (k, v) for k, v in sorted(_roots.items(),
                                                              key=lambda kv: -kv[1])[:8]))

    stores_missing = _missing_declared_stores()
    old_rows = len(re.findall(r"^- \*\*", old or "", re.M))
    shrink = old_rows - len(arts)
    if a.write and not a.allow_shrink and (stores_missing or shrink > 0):
        print("\ndev-docs index: REFUSING to write - this looks like a PARTIAL TREE.")
        if stores_missing:
            # The direct test, and it beats any threshold: the stores are DECLARED in the facet
            # vocabulary, so their absence is a fact about this checkout, not a judgement.
            print("   declared stores missing from this checkout: %s"
                  % ", ".join(sorted(stores_missing)[:6]))
        if shrink > 0:
            print("   %s currently lists %d artifact(s); this run found %d - a drop of %d."
                  % (OUT.name, old_rows, len(arts), shrink))
        print("   Regenerate from the main checkout, which holds the nested product repos.")
        print("   A genuine deletion? Re-run with --allow-shrink; it stays in the history as")
        print("   the claim that you looked.")
        return 1
    for p in problems:
        print("   PROBLEM: %s" % p)
    if problems and a.write:
        print("\n  Refusing to write while a marker is unresolved - fix the above first.")
        return 1
    if old == new:
        print("dev-docs index - %d artifact(s), %d section(s): the file matches the corpus."
              % (len(arts), len(SECTIONS)))
        return 0
    if a.write:
        OUT.write_text(new, encoding="utf-8", newline="")
        if generated_writes:
            generated_writes.record(WS, OUT.relative_to(WS).as_posix(), new)
        print("dev-docs index - wrote %s (%d artifacts, %d sections, %d orphan rows)"
              % (OUT.name, len(arts), len(SECTIONS), len(DATA.get("orphans", []))))
        return 0
    if stores_missing or shrink > 0:
        print("dev-docs index - this tree is PARTIAL; %s would lose %d row(s). Do NOT --write "
              "from here - regenerate from the main checkout." % (OUT.name, max(shrink, 0)))
        return 1
    print("dev-docs index - WOULD CHANGE %s (%d artifacts). Fix: dev_docs_index.py --write"
          % (OUT.name, len(arts)))
    return 1


def migrate_resolved_orphans():
    """Move a resolved orphan's authored text onto its artifact, then drop the orphan.

    Returns a list of human-readable lines describing what moved. Only ever called under
    --write; a dry run still reports the orphan as a problem so nothing changes silently.
    """
    moved = []
    remaining = []
    for o in DATA.get("orphans", []):
        target = Path(o["path"])
        if not target.exists():
            remaining.append(o)
            continue
        try:
            body = target.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            remaining.append(o)
            moved.append("could NOT read %s (%s) - orphan kept" % (target.name, exc))
            continue

        head = body.split("\n# ")[0]
        if SUMMARY.search(head):
            # The artifact already says it better than the orphan could. Drop the row
            # rather than overwrite an author's line with a stale one.
            moved.append("%s already carries its own summary - orphan row dropped"
                         % target.name)
            continue

        block = []
        if "dev-doc: section" not in head:
            block.append("<!-- dev-doc: section=%s order=%s -->"
                         % (o["section"], o.get("order", 50)))
            if o.get("title"):
                block.append("<!-- dev-doc-title: %s -->" % o["title"])
        block.append("<!-- summary: %s -->" % o["payload"].replace("-->", "--&gt;"))
        target.write_text("\n".join(block) + "\n" + body, encoding="utf-8", newline="")
        moved.append("moved the summary onto %s and dropped the orphan row" % target.name)

    if len(remaining) != len(DATA.get("orphans", [])):
        DATA["orphans"] = remaining
        DATA_FILE.write_text(json.dumps(DATA, indent=1, ensure_ascii=False) + "\n",
                             encoding="utf-8", newline="")
    return moved


def selftest():
    ok = True

    def t(label, cond):
        nonlocal ok
        print("  [%s] %s" % ("OK " if cond else "FAIL", label))
        ok &= bool(cond)

    print("dev_docs_index selftest")

    import datetime as _dt
    _today = _dt.date.today().strftime("%d-%b-%Y")
    _old = _stamp_line("01-Jan-2020") + "\n- **[a](x.md)** row\n"
    _newsame = _stamp_line(STAMP_MARK) + "\n- **[a](x.md)** row\n"
    _newdiff = _stamp_line(STAMP_MARK) + "\n- **[a](x.md)** row\n- **[b](y.md)** row\n"
    t("stamp KEEPS its date when no row moved",
      "01-Jan-2020" in _resolve_stamp(_newsame, _old))
    t("stamp MOVES to today when a row changed",
      _today in _resolve_stamp(_newdiff, _old))
    t("a first write with no previous file stamps today",
      _today in _resolve_stamp(_newsame, None))
    t("the placeholder never survives into the output",
      STAMP_MARK not in _resolve_stamp(_newsame, _old))
    t("the authored shape loaded", bool(SECTIONS))
    t("section slugs are unique", len(SECTION_ORDER) == len(SECTIONS))
    t("every section has a title", all(s.get("title") for s in SECTIONS))

    blk = ("<!-- dev-doc: section=x order=20 parent=p.md -->\n"
           "<!-- dev-doc-title: A Title -->\n"
           "<!-- summary: line one\nline two. **Status: planned.** -->\n")
    mk = read_markers(blk)
    t("the block we write is the block we read", bool(mk))
    t("...attrs round-trip", mk["attrs"] == {"section": "x", "order": "20", "parent": "p.md"})
    t("...the title round-trips", mk["title"] == "A Title")
    t("...a wrapped summary collapses to one line",
      mk["summary"] == "line one line two. **Status: planned.**")
    t("no marker is None, not an empty dict", read_markers("# nothing here") is None)
    t("a marker QUOTED inline (a table cell, a sentence) is not a declaration",
      read_markers("| 80 docs | each carries `<!-- dev-doc: section=x -->` |") is None)
    t("...but one at the start of a line is", read_markers(blk) is not None)

    fake = {"path": WS / "docs" / "specs" / "x.md", "title": "X", "summary": "*Spec* - s.",
            "attrs": {"section": "a", "order": "10"}}
