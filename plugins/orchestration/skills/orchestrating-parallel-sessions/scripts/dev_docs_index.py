DATA = _load()
STAMP_RE = re.compile(r"^\*\*Last updated: ([^*]+)\*\*")
STAMP_MARK = "<<LAST-UPDATED>>"


def _stamp_line(when):
    return ("**Last updated: %s** _(stamped when the rows last changed, never hand-written. "
            "A run that changes nothing keeps the date it found.)_" % when)


def _without_stamp(text):
    """Everything except the Last-updated line - so the date is never why the date changes."""
    return "\n".join(l for l in (text or "").split("\n") if not STAMP_RE.match(l))


def _resolve_stamp(new_text, old_text):
    """Today if the rows moved, otherwise the date already on disk. This is what converges.

    \u26d4 THE FIRST VERSION READ `git log -1` ON THIS FILE AND NEVER CONVERGED. Every landing
    is a commit touching it, so the next run computed a newer date than the file held, reported
    drift, was landed, and started over. Measured on a synced tree: the file said 09-Sep while
    the log said 18-Sep, with nothing else changed.

    \u2b50 `orchdoc.py`'s render_meta NAMES THIS TRAP - "the derived value cannot include
    itself" - and answers it with `landing_now`, because there the committing tool IS the caller.
    This generator commits nothing, so that answer does not transfer. **I quoted that comment
    while building the thing it warns about.**

    \u2b50 Comparing bodies WITHOUT the stamp is the whole trick: a run that changes no rows
    keeps the date it found, so a no-op run stays a no-op.
    """
    import datetime as _dt
    prev = None
    for l in (old_text or "").split("\n"):
        m = STAMP_RE.match(l)
        if m:
            prev = m.group(1).strip()
            break
    same = _without_stamp(new_text) == _without_stamp(old_text)
    when = prev if (same and prev) else _dt.date.today().strftime("%d-%b-%Y")
    return new_text.replace(_stamp_line(STAMP_MARK), _stamp_line(when))

SECTIONS = DATA.get("sections", [])
SECTION_ORDER = {s["slug"]: i for i, s in enumerate(SECTIONS)}


def collapse(s):
    return re.sub(r"\s+", " ", s).strip()


def read_markers(text):
    """{attrs, title, summary} for a marked artifact, or None. The ONE reader of the block."""
    m = DEV_DOC.search(text)
    if not m:
        return None
    attrs = {}
    for kv in m.group("attrs").split():
        if "=" in kv:
            k, v = kv.split("=", 1)
            attrs[k] = v
    t = DEV_TITLE.search(text)
    s = SUMMARY.search(text)
    return {"attrs": attrs,
            "title": collapse(t.group("t")) if t else None,
            "summary": collapse(s.group("s")) if s else None}


def harvest(base=None, skipped=None):
    """Every artifact carrying the marker, under the workspace or the memory store, less the
    LEFTOVERS: untracked files whose path origin/main's history deleted (leftover_files.py).

    `base` is the commit the nightly land step pinned, and makes the leftover test strict (it
    raises leftover_files.CannotCheck when it cannot run). None is a run by hand or by
    self-heal's check: origin/main, and every artifact kept when the test cannot run, as
    before. `skipped`, when a list, receives each leftover dropped."""
    found = []
    for store in (WS, MEM):
        if not store.exists():
            continue
        # ⛔ PRIVATE FOLDERS UNDER ANOTHER NAME (o9 W152, lane o9L1118). The walk below prunes a
        # private folder by its name, but Python 3.12's os.walk follows a junction, and a
        # junction to app-feedback reaches its files under the junction's own name. So the walk
        # starts in no private folder (private_folders.in_private_folder, which resolves the
        # real path), enters no junction or symbolic link to a folder, and reads no file that is
        # a symbolic link (private_folders.is_link). Testing is_link alone is enough below the
        # start folder: a walk that follows no link only meets real folders under their long
        # names, which the name test sees. On 2026-10-08 the one link this walk reached was the
        # dangling junction `.wt-pulse-journeys`, so no row of the index came through a link.
        if private_folders.in_private_folder(store):
            continue
        for root, dirs, files in os.walk(store):
            # Name-set first because it is free; then the path check, which is the only one
            # that can recognise a worktree - their basenames are generated and unguessable.
            # `.shared/cloud/memory/` and `.shared/cloud/global-rules.md` are cloud_publish.py's copies
            # of the memory notes and the global rules, which this walk reads where they are
            # written: harvesting both would list every marked note twice. The hand-kept
            # BUILD-RULES.md beside them is harvested (cloud_layout.is_generated_copy).
            dirs[:] = [d for d in dirs
                       if d not in SKIP_DIRS and not private_folders.is_private_name(d)
                       and not private_folders.is_link(os.path.join(root, d))
                       and not _in_other_worktree(os.path.join(root, d))
                       and not _is_gitless_lane_dir(root, d)
                       and not cloud_layout.is_generated_copy(os.path.join(root, d))]
            for f in files:
                if not f.endswith(".md"):
                    continue
                p = Path(root) / f
                if cloud_layout.is_generated_copy(p) or private_folders.is_link(p):
                    continue
                # ⛔ NEVER HARVEST A GENERATED VIEW, STARTING WITH THIS SCRIPT'S OWN OUTPUT.
                # The index quotes the marker syntax in its own header prose, so the first run
                # read the file it had just written and reported it as an artifact declaring
                # section `...`. A view that lists itself is the beginning of a loop.
                if p == OUT:
                    continue
                try:
                    raw = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    continue
                # ⛔ A MARKER PAST 8000 CHARACTERS WAS STILL A MARKER, and this reader's
                # number was its own - route.py used 3000, knowledge_gate 4000 - so a doc could
                # be routable and absent from this index with nothing reporting the difference.
                # `declaration_region` answers it once for every reader; fences are stripped so
                # a doc TEACHING the marker syntax does not index itself, which is the same
                # hazard the self-exclusion above guards from the other direction.
                head = outside_fences(declaration_region(raw, p))
                if "\n<!-- dev-doc:" not in head and not head.startswith("<!-- dev-doc:"):
                    continue
                if "<!-- GENERATED by" in head[:400]:
                    continue
                mk = read_markers(head)
                if mk:
                    found.append({"path": p, **mk})
    # ⛔ A LEFTOVER IS NOT AN ARTIFACT (o9:W149, o9's ruling of 2026-10-03 on lane o9L1027's
    # review). deliver.py writes and never deletes, so a doc deleted or moved on origin/main
    # stays in the main checkout untracked, and this walk listed it again: the deleted doc's
    # row came back, and a moved doc got a second row at a path origin/main no longer has.
    left = []
    found = leftover_files.drop(found, WS, base, left)
    if left:
        print(leftover_files.note(len(left)))
    if skipped is not None:
        skipped.extend(left)
    return found


def _linkable(p):
    """Inside the <your-workspace> repo itself - i.e. no intervening `.git` on the way down.

    ⛔ A LINK THAT DOES NOT OPEN IS WORSE THAN NO LINK. The preview pane can only follow a
    relative path inside this repo; a nested product repo or the memory store is somewhere else
    on disk, so those render as plain text plus their absolute path, exactly as the hand-kept
    file did.
    """
    try:
        rel = p.relative_to(WS)
    except ValueError:
        return None
    parts = rel.as_posix().split("/")
    for k in range(1, len(parts)):
        if (WS.joinpath(*parts[:k]) / ".git").exists():
            return None
    return rel.as_posix()


def _reader_ws():
    """The MAIN working tree - where a reader opens these files, not where we are generating.

    ⛔ `WS` resolves to the repo the CALLER is in, deliberately: a gate acting on the caller's
    tree must see that tree. But an INDEX is read somewhere else. Regenerating from a worktree
    wrote that worktree into every row - measured at 42 of 59 rows on origin/main - so the map
    the human opens pointed into a directory that exists only while that worktree does.

    ⭐ One constant was answering two questions. "Where am I working" and "where does the reader
    open this" are different, and only the second belongs in a row.
    """
    try:
        import subprocess
        r = subprocess.run(["git", "worktree", "list", "--porcelain"],
                           capture_output=True, text=True, timeout=15, cwd=str(WS),
                           creationflags=flags())
        for line in r.stdout.split("\n"):
            if line.startswith("worktree "):
                return Path(line[len("worktree "):].strip())
    except Exception:
        pass
    return WS


READER_WS = _reader_ws()


def _other_worktree_roots():
    """Every registered worktree EXCEPT the one a reader opens - the directories to never walk.

    ⛔ MEASURED 2026-09-08, reported by o1: DEV-DOCS-INDEX.md carried 91 rows pointing inside
    `.claude/worktrees/*` and `.wt-*`. Same artifact listed two and three times, at paths that
    vanish with the worktree - the exact failure the index rule names.

    ⭐ `_reader_ws()` above already fixed the SIBLING of this and its docstring says so: it stops
    a worktree being written INTO every row when generating FROM one. This is generating INTO a
    worktree, one level over, and the authoritative list was already in the call it makes - it
    just took the first line and dropped the rest.

    ⛔ WHY A NAME-SET CANNOT DO THIS. `SKIP_DIRS` matches `d not in SKIP_DIRS`, so it would need
    every worktree's basename - and those are generated (`nostalgic-hermann-495856`,
    `.wt-o8L131-at-audit`) and change every time one is created. Pruning by RESOLVED PATH against
    git's own list is the only version that stays true.

    ⚠️ Only worktrees NESTED INSIDE the walk root can be reached at all; the ones under
    `<your-workspace>-worktrees/` are siblings and were never the problem. Both are pruned anyway,
    because which are nested is a fact about today's layout.
    """
    roots = set()
    try:
        import subprocess
        r = subprocess.run(["git", "worktree", "list", "--porcelain"],
                           capture_output=True, text=True, timeout=15, cwd=str(WS),
                           creationflags=flags())
        main = None
        for line in r.stdout.split("\n"):
            if not line.startswith("worktree "):
                continue
            p = Path(line[len("worktree "):].strip())
            if main is None:
                main = p.resolve()
                continue
            try:
                roots.add(p.resolve())
            except OSError:
                continue
    except Exception:
        pass                       # no git, no prune - the walk is then what it always was
    return roots


OTHER_WORKTREES = _other_worktree_roots()


def _is_worktree_dir(path):
    """True when this directory is a WORKTREE of some repo rather than a repo of its own.

    ⛔ THE REGISTRY GOES STALE, AND THE PRUNE ABOVE TRUSTS IT. o1 found two phantom rows return
    from `.wt-feature-test` and `wt-o10L50f`: both carry their own `.git`, and NEITHER appears
    in `git worktree list --porcelain`. So they are orphaned or detached, and a prune keyed on
    git's registration cannot see them.

    ⭐ THAT IS THE SHAPE THIS FILE ALREADY CARRIES A FIX FOR, landing on the fix itself. Asking
    git "what are your worktrees?" gets a truthful answer ABOUT ITS OWN REGISTRY, which is not
    the question "what worktree-shaped directories exist here". An instrument answering about
    itself, one level up from the last time.

    ⛔ o1's proposed distinguisher - a worktree shares `origin` with the workspace, a product
    repo does not - was offered as a guess and MEASURED WRONG: it matched 0 of them, because an
    orphaned worktree has no usable origin at all and therefore sorts with the product repos.
    Their instinct to flag it as a guess was right.

    ⭐ The structural property is exact and needs no git process: git leaves a worktree a `.git`
    FILE containing `gitdir: ...`, while a real repository has a `.git` DIRECTORY. Measured
    across this workspace: 17 real repos have a directory and are kept - including
    `product-app` and `product-website`, which are legitimately indexed at 11 rows
    each - while every worktree-shaped directory has a file, registered or not.

    ⚠️ Keeps the registry check as well. A REGISTERED worktree can live outside this walk root,
    and the two tests fail in different ways, which is the point of having both.
    """
    try:
        g = Path(path) / ".git"
        return g.is_file()
    except OSError:
        return False


def _is_gitless_lane_dir(parent, name):
    """True for a child of a worktree root (`worktrees`, `*-worktrees`) that has no `.git`.

    A lane folder with no `.git` (file or directory) is scratch left behind after its worktree
    was removed, not a checkout. The nightly commit c40f93ca (2026-10-06) indexed 11 rows from
    `product-app-worktrees/o10L*/todo.md` that way; third occurrence (o9:W162).
    """
    root_name = os.path.basename(os.path.normpath(parent)).lower()
    if root_name != "worktrees" and not root_name.endswith("-worktrees"):
        return False
    try:
        return not (Path(parent) / name / ".git").exists()
    except OSError:
        return False


def _in_other_worktree(path):
    """True when this directory IS, or sits inside, a worktree that is not the reader's."""
    if _is_worktree_dir(path):
        return True
    try:
        rp = Path(path).resolve()
    except OSError:
        return False
    for root in OTHER_WORKTREES:
        if rp == root or root in rp.parents:
            return True
    return False


def _as_reader_path(p):
    """Re-root an absolute path under the MAIN worktree when it sits inside ours."""
    try:
        return (READER_WS / Path(p).relative_to(WS)).as_posix()
    except (ValueError, TypeError):
        return Path(p).as_posix()


def render_row(a, indent=0):
    at = a["attrs"]
    rel = _linkable(a["path"])
    href = at.get("url") or rel
    title = a["title"] or a["path"].name
    head = "**[%s](%s)**" % (title, href) if href else "**%s**" % title
    shown = at.get("path")
    if shown:
        disp = shown if shown.startswith("C:") else (READER_WS / shown).as_posix()
        if shown.endswith("/"):
            disp = disp.rstrip("/") + "/"
    else:
        disp = _as_reader_path(a["path"])
    cols = [head, "`%s`" % disp]
    if at.get("also"):
        cols[-1] += " (+ `%s`)" % at["also"]
    cols.append(a["summary"] or "")
    return "%s- %s" % (" " * indent, " \u00b7 ".join(c for c in cols if c))


def render_orphan(o):
    head = "**[%s](%s)**" % (o["title"], o["href"]) if o.get("href") else "**%s**" % o["title"]
    return ("- \u26a0 **TARGET NOT ON DISK** - %s \u00b7 `%s` \u00b7 %s\n"
            "  \u21b3 *%s. Its authored text is held in `dev_docs_sections.json` until the file "
            "exists; nothing was dropped.*" % (head, o["path"], o["payload"], o["why"]))


def build(base=None, skipped=None):
    """(lines, problems, artifacts) - the whole file, and anything that stopped it being clean.
    `base` and `skipped` go to harvest()."""
    arts = harvest(base, skipped)
    problems = []
    by_section = {}
    for a in arts:
        slug = a["attrs"].get("section")
        if slug not in SECTION_ORDER:
            problems.append("%s declares unknown section `%s`" % (a["path"].name, slug))
            continue
        if not a["summary"]:
            problems.append("%s carries a dev-doc marker but no <!-- summary: --> line"
                            % a["path"].name)
        by_section.setdefault(slug, []).append(a)

    orphans = {}
    for o in DATA.get("orphans", []):
        orphans.setdefault(o["section"], []).append(o)
        if Path(o["path"]).exists():
            problems.append("orphan RESOLVED - %s now exists; move its text onto the artifact "
                            "and delete the orphan entry (run --write to do it automatically)"
                            % o["path"])

    L = [BANNER, "", "# %s" % DATA.get("h1", "DEV-DOCS-INDEX"), "",
         _stamp_line(STAMP_MARK), "",
         DATA.get("header", ""), "",
         "**How this file is built.** Membership and every path are DERIVED: a doc appears "
         "here because it carries a `<!-- dev-doc: section=... -->` marker, and its path is "
         "wherever the file actually is - so a doc that moves takes its row with it. The "
         "one-line summary is authored and lives ON the artifact as `<!-- summary: ... -->`, "
         "which is why deleting this file loses nothing. Section groupings and their intro "
         "prose are authored in `.shared/scripts/dev_docs_sections.json`. Regenerate with "
         "`python .shared/scripts/dev_docs_index.py --write`.", "",
         "---", ""]

    for s in SECTIONS:
        rows = by_section.get(s["slug"], [])
        orph = orphans.get(s["slug"], [])
        L += ["## %s" % s["title"], ""]
        if s.get("intro"):
            L += [s["intro"], ""]
        if not rows and not orph:
            L += ["*Nothing carries `section=%s` today. That is a finding, not a formatting "
                  "gap.*" % s["slug"], ""]
        # parents first, each followed by its children, then the rest, all by declared order.
        kids = {}
        for a in rows:
            par = a["attrs"].get("parent")
            if par:
                kids.setdefault(par, []).append(a)
        top = [a for a in rows if not a["attrs"].get("parent")]
        top.sort(key=lambda a: int(a["attrs"].get("order", 0)))
        for a in top:
            L.append(render_row(a))
            for k in sorted(kids.get(a["path"].name, []),
                            key=lambda x: int(x["attrs"].get("order", 0))):
                L.append(render_row(k, indent=2))
        for k, v in kids.items():
            if k not in {a["path"].name for a in top}:
                problems.append("parent=%s named by %s is not in this section"
                                % (k, ", ".join(x["path"].name for x in v)))
        for o in sorted(orph, key=lambda x: x["order"]):
            L.append(render_orphan(o))
        L += [""]
        if s.get("rule_after"):
            L += ["---", ""]

    L += ["---", "", "## %s" % DATA.get("excluded_title", "Excluded (and why)"), "",
          DATA.get("excluded", ""), ""]
    return L, problems, arts


def cmd_check():
    _, problems, arts = build()
    print("dev-docs index - marker health")
    print()
    print("  artifacts carrying a dev-doc marker : %d" % len(arts))
    print("  orphan rows (no artifact on disk)   : %d" % len(DATA.get("orphans", [])))
    for o in DATA.get("orphans", []):
        print("     - %s  (%s)" % (o["path"], o["why"]))
    print("  problems                            : %d" % len(problems))
    for p in problems:
        print("     - %s" % p)
    print()
    if problems:
        print("  Each problem above is a row that will not render where it should.")
        return 1
    print("  every marker resolves to a known section, with a summary.")
    return 0


def _missing_declared_stores():
    """Declared nested product repos that are ABSENT from this checkout.

    ⭐ THE DIRECT TEST, AND IT NEEDS NO THRESHOLD. A partial tree is not a small drop - it is
    whole stores gone at once, and those stores are DECLARED in facets_vocabulary.json. Their
    absence is a fact about this checkout rather than a judgement about a count, which is why
    this runs first and the row-count comparison is only the net beneath it.

    A worktree is the ordinary way to land here: `git worktree add` checks out this repo and
    nothing else, so every nested product repo is missing and the generator sees a corpus less
    than half the size with no indication anything is wrong.
    """
    try:
        raw = json.loads((Path(__file__).resolve().parent
                          / "facets_vocabulary.json").read_text(encoding="utf-8"))
        repos = [n for n in raw.get("nested_repos", []) if n]
    except Exception:
        return []                        # no vocabulary, no claim - the count check still runs
    return [r for r in repos if not (WS / r).is_dir()]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--allow-shrink", action="store_true",
                    help="write even though the index would lose rows - for a genuine "
                         "deletion, never to get past a partial tree")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if not DATA:
        # ⛔ NO SHAPE MEANS WRITE NOTHING. With no sections every artifact is "unknown section"
        # and an unguarded --write would replace the index with an empty skeleton - a generator
        # erasing the map because its vocabulary file was missing.
        print("dev-docs index: no %s - nothing generated, nothing on disk touched."
              % DATA_FILE.name)
        return 0
    if a.check:
        return cmd_check()
    if a.write:
        # Self-clearing: a resolved orphan is migrated rather than reported, so it can
        # never again be the reason this index refuses to write. See the function.
        for line in migrate_resolved_orphans():
            print("   MIGRATED: %s" % line)
    lines, problems, arts = build()
    # ⛔ A SCAN THAT FINDS NOTHING IS A BROKEN SCAN, NOT AN EMPTY CORPUS. Every row lives on an
    # artifact, so a checkout missing them - a partial clone, a wrong cwd, a walk that hit a
    # permissions error - would otherwise regenerate this file as sixteen empty headings and
    # destroy the map. knowledge_pages.py declines for the same reason when its tree is absent:
    # for a READER "detects nothing" is right; for a WRITER the equivalent is to refuse, loudly.
    if not arts and OUT.exists():
        print("dev-docs index: the scan found ZERO marked artifacts while %s exists."
              % OUT.name)
        print("   That is a broken scan, not an empty corpus - refusing to overwrite the map.")
        return 1
    new = "\n".join(lines).rstrip("\n") + "\n"
    old = OUT.read_text(encoding="utf-8", errors="replace") if OUT.exists() else None
    # The stamp is decided HERE, where both texts exist, and only from whether the
    # rows moved - so the `old == new` test below stays a true test of convergence.
    new = _resolve_stamp(new, old)

    # ⛔ THE GUARD ABOVE FIRES AT ZERO, AND A PARTIAL TREE DOES NOT PRODUCE ZERO. Found by o1,
    # 2026-09-08, from a live loss: a session's commit touched a `dev-doc:`-marked file, the
    # index regenerated as a side effect from a tree without the nested product repos, and 38
    # real rows were deleted - every product-app/docs and product-website/docs spec,
    # the o6 keyword plan, the quiz, the script-writing research, and an artifact whose marker
    # o1 had added an hour earlier precisely to get it indexed. Reproduced here: a worktree
    # yields 47 artifacts where the full checkout yields 85, and the tool printed
    # "Fix: dev_docs_index.py --write" - inviting it.
    #
    # ⭐ THE REASONING OF THE ZERO GUARD WAS ALREADY RIGHT AND ITS TRIGGER WAS TOO NARROW. "For
    # a READER detects-nothing is right; for a WRITER the equivalent is to refuse, loudly." A
    # 46% shrink is the same event as a zero, arriving quietly.
    #
    # ⛔ WHY THIS IS WORSE THAN THE TWO EARLIER FALSE ALL-CLEARS ON THIS FILE. Phantom rows were
    # noise anyone could see. This DELETES real rows, looks like an ordinary regeneration, and
    # the session that caused it gets no signal - so a doc can be marked, landed, verified
    # indexed, and silently de-indexed hours later by an unrelated commit.
    # ⭐ THE PUSHBULLET SESSION'S ADDITION, 2026-09-08, and it earns its line: they watched the
    # artifact count go 171 -> 61 -> 47 across three runs and said "nothing in its output
    # treated that as a fault". A refusal only speaks when someone writes. This prints on EVERY
    # run, so a missing root is visible to a read-only check too - which is how the partial tree
    # would have announced itself before their commit rather than after o1 found the loss.
    _roots = {}
    for _a in arts:
        try:
            _rel = Path(_a["path"]).resolve().relative_to(WS.resolve()).parts
        except Exception:
            _roots["(memory)"] = _roots.get("(memory)", 0) + 1
            continue
        _roots[_rel[0] if len(_rel) > 1 else "(workspace root)"] = \
            _roots.get(_rel[0] if len(_rel) > 1 else "(workspace root)", 0) + 1
    if _roots:
        print("   markers per root: %s"
              % ", ".join("%s %d" % (k, v) for k, v in sorted(_roots.items(),
                                                              key=lambda kv: -kv[1])[:8]))

    stores_missing = _missing_declared_stores()
    old_rows = len(re.findall(r"^- \*\*", old or "", re.M))
    shrink = old_rows - len(arts)
    if a.write and not a.allow_shrink and (stores_missing or shrink > 0):
        print("\ndev-docs index: REFUSING to write - this looks like a PARTIAL TREE.")
        if stores_missing:
            # The direct test, and it beats any threshold: the stores are DECLARED in the facet
            # vocabulary, so their absence is a fact about this checkout, not a judgement.
            print("   declared stores missing from this checkout: %s"
                  % ", ".join(sorted(stores_missing)[:6]))
        if shrink > 0:
            # ⭐ THRESHOLD SET FROM HISTORY, NOT TASTE. Across the last 20 revisions of this
            # file the count moved +1 to +4, and the ONLY decrease was a -24 that was itself
            # almost certainly this bug. The index has never legitimately shrunk, so any
            # decrease is worth one sentence before it is written.
            print("   %s currently lists %d artifact(s); this run found %d - a drop of %d."
                  % (OUT.name, old_rows, len(arts), shrink))
        print("   Regenerate from the main checkout, which holds the nested product repos.")
        print("   A genuine deletion? Re-run with --allow-shrink; it stays in the history as")
        print("   the claim that you looked.")
        return 1
    for p in problems:
        print("   PROBLEM: %s" % p)
    if problems and a.write:
        print("\n  Refusing to write while a marker is unresolved - fix the above first.")
        return 1
    if old == new:
        print("dev-docs index - %d artifact(s), %d section(s): the file matches the corpus."
              % (len(arts), len(SECTIONS)))
        return 0
    if a.write:
        OUT.write_text(new, encoding="utf-8", newline="")
        print("dev-docs index - wrote %s (%d artifacts, %d sections, %d orphan rows)"
              % (OUT.name, len(arts), len(SECTIONS), len(DATA.get("orphans", []))))
        return 0
    # ⛔ AND THE READ-ONLY RUN MUST NOT RECOMMEND THE DESTRUCTIVE ACT. The refusal above only
    # speaks to someone who already typed --write; this line is what a session READS FIRST, and
    # it was saying "Fix: --write" from a partial tree - the tool naming the command that
    # deletes the rows. That is how the 04:57 loss happened: the operator did what the output
    # told them to.
    if stores_missing or shrink > 0:
        print("dev-docs index - this tree is PARTIAL; %s would lose %d row(s). Do NOT --write "
              "from here - regenerate from the main checkout." % (OUT.name, max(shrink, 0)))
        return 1
    print("dev-docs index - WOULD CHANGE %s (%d artifacts). Fix: dev_docs_index.py --write"
          % (OUT.name, len(arts)))
    return 1


def migrate_resolved_orphans():
    """Move a resolved orphan's authored text onto its artifact, then drop the orphan.

    ⛔ WHY THIS IS AUTOMATIC AND NOT A REPORTED PROBLEM. An orphan row exists to hold a
    summary for an artifact that does not exist yet. The moment the artifact appears, the
    row has done its job - but nothing was obliged to notice, so it sat there. And because
    an unresolved marker makes this generator REFUSE to write, one stale row froze the
    whole index.

    Measured 2026-09-08: the row for PWA-SOURCE-OF-TRUTH.md resolved on 2026-08-11 and
    nobody cleared it, so DEV-DOCS-INDEX.md could not accept a single new artifact for
    four weeks. The index header still read "Last updated: 2026-08-11" - the last day a
    write succeeded. o9 then measured the other half: NOTHING RAN THIS SCRIPT AT ALL
    (now a report-only step in morning_self_heal.py, 936d62b). Two independent causes,
    one symptom.

    ⭐ THE SHAPE WORTH REMEMBERING: a guard that keeps firing after its cause is gone is
    indistinguishable from a guard that is working. It prints a confident, accurate
    diagnosis every run. The fix is not a better message - it is removing the state that
    can be stale, by making the resolution the same act as the detection.

    Returns a list of human-readable lines describing what moved. Only ever called under
    --write; a dry run still reports the orphan as a problem so nothing changes silently.
    """
    moved = []
    remaining = []
    for o in DATA.get("orphans", []):
        target = Path(o["path"])
        if not target.exists():
            remaining.append(o)
            continue
        try:
            body = target.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            remaining.append(o)
            moved.append("could NOT read %s (%s) - orphan kept" % (target.name, exc))
            continue

        head = body.split("\n# ")[0]
        if SUMMARY.search(head):
            # The artifact already says it better than the orphan could. Drop the row
            # rather than overwrite an author's line with a stale one.
            moved.append("%s already carries its own summary - orphan row dropped"
                         % target.name)
            continue

        block = []
        if "dev-doc: section" not in head:
            block.append("<!-- dev-doc: section=%s order=%s -->"
                         % (o["section"], o.get("order", 50)))
            if o.get("title"):
                block.append("<!-- dev-doc-title: %s -->" % o["title"])
        block.append("<!-- summary: %s -->" % o["payload"].replace("-->", "--&gt;"))
        target.write_text("\n".join(block) + "\n" + body, encoding="utf-8", newline="")
        moved.append("moved the summary onto %s and dropped the orphan row" % target.name)

    if len(remaining) != len(DATA.get("orphans", [])):
        DATA["orphans"] = remaining
        DATA_FILE.write_text(json.dumps(DATA, indent=1, ensure_ascii=False) + "\n",
                             encoding="utf-8", newline="")
    return moved


def selftest():
    ok = True

    def t(label, cond):
        nonlocal ok
        print("  [%s] %s" % ("OK " if cond else "FAIL", label))
        ok &= bool(cond)

    print("dev_docs_index selftest")

    # ⭐ THE STAMP, BOTH DIRECTIONS. The first version of this field read `git log -1` on
    # the index, so every landing made the next run differ - a generator that never converged.
    # A no-op run keeping its date is the half that was broken; a real change moving it is the
    # half that makes the field worth having. Neither is safe to leave untested.
    import datetime as _dt
    _today = _dt.date.today().strftime("%d-%b-%Y")
    _old = _stamp_line("01-Jan-2020") + "\n- **[a](x.md)** row\n"
    _newsame = _stamp_line(STAMP_MARK) + "\n- **[a](x.md)** row\n"
    _newdiff = _stamp_line(STAMP_MARK) + "\n- **[a](x.md)** row\n- **[b](y.md)** row\n"
    t("stamp KEEPS its date when no row moved",
      "01-Jan-2020" in _resolve_stamp(_newsame, _old))
    t("stamp MOVES to today when a row changed",
      _today in _resolve_stamp(_newdiff, _old))
    t("a first write with no previous file stamps today",
      _today in _resolve_stamp(_newsame, None))
    t("the placeholder never survives into the output",
      STAMP_MARK not in _resolve_stamp(_newsame, _old))
    t("the authored shape loaded", bool(SECTIONS))
    t("section slugs are unique", len(SECTION_ORDER) == len(SECTIONS))
    t("every section has a title", all(s.get("title") for s in SECTIONS))

    blk = ("<!-- dev-doc: section=x order=20 parent=p.md -->\n"
           "<!-- dev-doc-title: A Title -->\n"
           "<!-- summary: line one\nline two. **Status: planned.** -->\n")
    mk = read_markers(blk)
    t("the block we write is the block we read", bool(mk))
    t("...attrs round-trip", mk["attrs"] == {"section": "x", "order": "20", "parent": "p.md"})
    t("...the title round-trips", mk["title"] == "A Title")
    # ⭐ A WRAPPED SUMMARY MUST COLLAPSE TO ONE LINE, or a row breaks the bullet it lives in.
    t("...a wrapped summary collapses to one line",
      mk["summary"] == "line one line two. **Status: planned.**")
    t("no marker is None, not an empty dict", read_markers("# nothing here") is None)
    t("a marker QUOTED inline (a table cell, a sentence) is not a declaration",
      read_markers("| 80 docs | each carries `<!-- dev-doc: section=x -->` |") is None)
    t("...but one at the start of a line is", read_markers(blk) is not None)

    # ⛔ THE FAILURE THAT MADE THIS A VIEW: a row pointing at a directory the file left. The
    # path is derived, so it cannot say anything but where the file is.
    fake = {"path": WS / "docs" / "specs" / "x.md", "title": "X", "summary": "*Spec* - s.",
            "attrs": {"section": "a", "order": "10"}}
    t("a repo-internal artifact renders a clickable relative link",
      "(docs/specs/x.md)" in render_row(fake))
    out = render_row({"path": MEM / "y.md", "title": "Y", "summary": "s",
                      "attrs": {"section": "a", "order": "10"}})
    t("an artifact OUTSIDE this repo renders no link (it would not open)",
      out.startswith("- **Y** \u00b7") and "](" not in out)
    t("...but still carries its absolute path", str(MEM.as_posix()) in out)
    t("an authored url= overrides the derived link",
      "(https://e.example/x)" in render_row({**fake, "attrs": {"section": "a", "order": "1",
                                                               "url": "https://e.example/x"}}))
    # READER_WS, not WS: an authored path= is still re-rooted to where the READER opens it.
    # The property under test is unchanged - an authored path overrides the derived one - only
    # the root it is rendered against moved, which is the fix this fixture now pins.
    t("an authored path= overrides the shown path (a row that points at a folder)",
      "`%s/product_page_1/`" % READER_WS.as_posix()
      in render_row({**fake, "attrs": {"section": "a", "order": "1",
                                       "path": "product_page_1/"}}))

    # ⛔ AN ORPHAN MUST BE LOUD. A row whose artifact is gone used to just sit there reading
    # like every other row; silently dropping it instead would be the data loss this conversion
    # was told to avoid.
    o = render_orphan({"title": "T", "path": "C:/gone.md", "payload": "*x* - y",
                       "href": None, "why": "not present"})
    t("an orphan row is rendered, and marked", "TARGET NOT ON DISK" in o and "*x* - y" in o)

    # ⛔ NEGATIVE CONTROL, and the only test here that can see a destructive bug. Every row
    # lives on an artifact, so a scan that reaches none of them looks exactly like "the corpus
    # is empty" - and the honest-looking response, writing what you found, erases the map.
    if OUT.exists():
        real, before = harvest, OUT.read_text(encoding="utf-8", errors="replace")
        try:
            globals()["harvest"] = lambda *_a, **_k: []
            argv, sys.argv = sys.argv, ["dev_docs_index.py", "--write"]
            rc = main()
        finally:
            globals()["harvest"], sys.argv = real, argv
        t("an empty harvest REFUSES rather than blanking the index", rc == 1)
        t("...and the file on disk is untouched",
          OUT.read_text(encoding="utf-8", errors="replace") == before)

    # ⛔ A LEFTOVER LANE FOLDER IS NOT A DOC. Walk a real temporary tree: a marker in a normal
    # folder is found; the same marker in a `.worktrees/<lane>/` folder with NO `.git` - the
    # shape a removed worktree of a NESTED repo leaves - is not. The control proves the walk ran.
    import tempfile as _tf
    import shutil as _sh
    _tmp = Path(_tf.mkdtemp(prefix="ddi-"))
    _mark = ("<!-- dev-doc: section=x order=10 -->\n<!-- dev-doc-title: T -->\n"
             "<!-- summary: s -->\n")
    try:
        for rel in ("docs/real.md", "nested-repo/.worktrees/o10L60/todo.md",
                    "x-worktrees/withgit/todo.md", "x-worktrees/nogit/todo.md"):
            (_tmp / rel).parent.mkdir(parents=True, exist_ok=True)
            (_tmp / rel).write_text(_mark, encoding="utf-8")
        # o9:W162: under a `*-worktrees` root a child with a `.git` is kept, one without is not.
        (_tmp / "x-worktrees" / "withgit" / ".git").mkdir()
        _saved = (globals()["WS"], globals()["MEM"])
        try:
            globals()["WS"], globals()["MEM"] = _tmp, _tmp / "no-memory-here"
            _got = sorted(Path(a["path"]).relative_to(_tmp).as_posix() for a in harvest())
        finally:
            globals()["WS"], globals()["MEM"] = _saved
        t("CONTROL: a marker in an ordinary folder is harvested", "docs/real.md" in _got)
        t("a marker inside a leftover `.worktrees/<lane>/` folder is NOT",
          not any(".worktrees/" in g for g in _got))
        t("o9:W162 a `*-worktrees/<lane>/` folder WITH a `.git` is harvested",
          "x-worktrees/withgit/todo.md" in _got)
        t("o9:W162 a `*-worktrees/<lane>/` folder with NO `.git` is skipped",
          "x-worktrees/nogit/todo.md" not in _got)

        # ⛔ o9 W152 (lane o9L1118): A PRIVATE FOLDER UNDER ANOTHER NAME. Made-up marked files
        # in a folder named `app-feedback` and in a plain folder, both OUTSIDE the walked tree,
        # each reached through a junction inside it. Each check marked "failed before" failed
        # on the walk before this fix. A store that starts inside app-feedback is not walked.
        _out = Path(_tf.mkdtemp(prefix="ddi-out-"))
        _links = []
        try:
            for rel in ("app-feedback/secret.md", "plain/other.md"):
                (_out / rel).parent.mkdir(parents=True, exist_ok=True)
                (_out / rel).write_text(_mark, encoding="utf-8")
            _ws2 = _tmp / "ws2"
            (_ws2 / "docs").mkdir(parents=True)
            (_ws2 / "docs" / "real.md").write_text(_mark, encoding="utf-8")
            _made = True
            for target, link in ((_out / "app-feedback", _ws2 / "aliases"),
                                 (_out / "plain", _ws2 / "plain_link")):
                try:
                    import _winapi
                    _winapi.CreateJunction(str(target), str(link))
                except Exception:
                    try:
                        os.symlink(target, link, target_is_directory=True)
                    except Exception:
                        _made = False
                        continue
                _links.append(link)
            _saved = (globals()["WS"], globals()["MEM"])
            try:
                globals()["WS"], globals()["MEM"] = _ws2, _out / "app-feedback"
                _got2 = sorted(Path(a["path"]).relative_to(_ws2).as_posix()
                               if str(a["path"]).startswith(str(_ws2)) else str(a["path"])
                               for a in harvest())
            finally:
                globals()["WS"], globals()["MEM"] = _saved
            t("W152 CONTROL: the marked file in an ordinary folder is harvested",
              "docs/real.md" in _got2)
            t("W152 a store that starts inside app-feedback is not walked (failed before)",
              not any("secret.md" in g and not g.startswith("aliases/") for g in _got2))
            if not _made:
                print("  NOTE: no junction or folder link could be made here; link cases skipped")
            else:
                t("W152 nothing is harvested through a junction to app-feedback (failed before)",
                  not any(g.startswith("aliases/") for g in _got2))
                t("W152 the walk follows no junction, even to a plain folder (failed before)",
                  not any(g.startswith("plain_link/") for g in _got2))
                t("W152 the whole harvest is the one ordinary file", _got2 == ["docs/real.md"])
        finally:
            for link in reversed(_links):
                try:
                    os.rmdir(link)              # a junction or folder link: the link only
                except OSError:
                    try:
                        os.unlink(link)
                    except OSError:
                        pass
            _sh.rmtree(_out, ignore_errors=True)
    finally:
        _sh.rmtree(_tmp, ignore_errors=True)

    t("the banner names the generator and forbids hand-editing",
      "GENERATED by .shared/scripts/dev_docs_index.py" in BANNER and "do not hand-edit" in BANNER)
    print("\nselftest %s" % ("PASSED" if ok else "FAILED"))
    return 0 if ok else 1


